"""Generate BACKLOG.md and per-story GitHub issue bodies from backlog/stories.json."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORIES_PATH = ROOT / "backlog" / "stories.json"
PRIORITY_ORDER = ["Must have", "Should have", "Could have", "Won't have"]


def story_body(story: dict) -> str:
    lines = [
        f"### User Story\n\n{story['story']}\n",
        "### Acceptance Criteria\n",
    ]
    for index, (given, when, then) in enumerate(story.get("ac", []), start=1):
        lines.extend([
            f"**Scenario {index}**",
            f"- **Given** {given}",
            f"- **When** {when}",
            f"- **Then** {then}\n",
        ])
    lines.extend([
        "### Planning\n",
        f"- **Role:** {story.get('role', 'N/A')}",
        f"- **MoSCoW:** {story['priority']}",
        f"- **Story Points:** {story['points']}",
        f"- **Platform:** {', '.join(story.get('platform', [])) or 'N/A'}",
        f"- **Dependencies:** {', '.join(story.get('dependencies', [])) or 'None'}",
    ])
    if story.get("note"):
        lines.extend(["", f"> {story['note']}\n"])
    lines.extend([
        "### Definition of Done\n",
        "- [ ] Acceptance Criteria satisfied",
        "- [ ] Relevant tests pass",
        "- [ ] Authorization/resource access checked",
        "- [ ] Documentation updated where needed",
        "- [ ] Review/self-review completed",
    ])
    return "\n".join(lines).strip() + "\n"


def main() -> None:
    stories = json.loads(STORIES_PATH.read_text(encoding="utf-8"))
    out_dir = ROOT / "backlog" / "issues"
    out_dir.mkdir(parents=True, exist_ok=True)

    counts = {priority: 0 for priority in PRIORITY_ORDER}
    totals = {priority: 0 for priority in PRIORITY_ORDER}
    lines = [
        "# FixIt — Complete Product Backlog\n",
        "Source of truth: `backlog/stories.json`. Generated by `scripts/build_backlog.py`.\n",
        "## MoSCoW Summary\n",
        "| Priority | Stories | Count | Story Points |",
        "|---|---|---:|---:|",
    ]
    for story in stories:
        priority = story["priority"]
        counts[priority] += 1
        totals[priority] += int(story["points"])
    for priority in PRIORITY_ORDER:
        ids = ", ".join(s["id"] for s in stories if s["priority"] == priority) or "—"
        lines.append(f"| {priority} | {ids} | {counts[priority]} | {totals[priority]} |")
    lines.append(f"| **Total** | **All Stories** | **{len(stories)}** | **{sum(int(s['points']) for s in stories)}** |\n")

    for story in stories:
        body = story_body(story)
        (out_dir / f"{story['id']}.md").write_text(body, encoding="utf-8")
        lines.append(f"## {story['id']}: {story['title']}\n")
        lines.append(body)

    (ROOT / "BACKLOG.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated BACKLOG.md and {len(stories)} issue markdown files.")


if __name__ == "__main__":
    main()
